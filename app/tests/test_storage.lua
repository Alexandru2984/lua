local lfs=require 'lfs'
local sqlite=require 'lsqlite3'
local storage,prefix,old_ngx,old_storage
describe('Private report storage and retention',function()
    before_each(function()
        prefix=os.tmpname();os.remove(prefix);assert(lfs.mkdir(prefix));assert(lfs.mkdir(prefix..'/data'))
        old_ngx=_G.ngx;old_storage=package.loaded.storage
        _G.ngx={config={prefix=function()return prefix..'/'end},time=function()return 1800000000 end,log=function()end,ERR=3}
        package.loaded.storage=nil;storage=require 'storage';assert(storage.init())
    end)
    after_each(function()
        package.loaded.storage=old_storage;_G.ngx=old_ngx
        for file in lfs.dir(prefix..'/data') do if file~='.' and file~='..' then os.remove(prefix..'/data/'..file) end end
        lfs.rmdir(prefix..'/data');lfs.rmdir(prefix)
    end)
    it('enforces ownership on reads favorites and deletion',function()
        local id=assert(storage.create('alice','example.com','quick'))
        assert.is_nil(storage.get('bob',id));assert.equal(0,storage.favorite('bob',id,true));assert.equal(0,storage.delete('bob',id))
        assert.equal(1,storage.count('alice'));assert.equal(0,storage.count('bob'))
        assert.equal(1,storage.favorite('alice',id,true));assert.equal(1,storage.get('alice',id).favorite)
        assert.equal(0,storage.delete('alice',id)) -- A running report is protected.
        assert(storage.finish(id,{error='Unavailable'},'failed',10));assert.is_nil(storage.get('alice',id).score)
        assert.equal(1,storage.delete('alice',id))
    end)
    it('keeps SQL payloads as bound text and preserves a real zero score',function()
        local id=assert(storage.create('alice',"example.com'; DROP TABLE scans;--",'quick'))
        assert(storage.finish(id,{score=0},'completed',10));assert.equal(0,storage.get('alice',id).score)
        assert.equal(1,storage.count('alice'));assert(storage.init())
    end)
    it('expires old owned reports while preserving unclaimed legacy data',function()
        local db=sqlite.open(prefix..'/data/recon.db')
        assert.equal(sqlite.OK,db:exec("INSERT INTO scans(target,created_epoch,status) VALUES ('legacy.example.com',1,'completed')"))
        assert.equal(sqlite.OK,db:exec("INSERT INTO scans(target,owner,created_epoch,status) VALUES ('old.example.com','alice',1,'completed')"))
        db:close();assert(storage.maintain());assert.equal(0,storage.count('alice'))
        db=sqlite.open(prefix..'/data/recon.db');local count
        for row in db:nrows('SELECT COUNT(*) AS n FROM scans WHERE owner IS NULL')do count=row.n end
        db:close();assert.equal(1,count)
    end)
    it('recovers stale pending jobs after interruptions',function()
        local id=assert(storage.create('alice','example.com','deep'))
        local db=sqlite.open(prefix..'/data/recon.db');db:exec('UPDATE scans SET created_epoch=1');db:close()
        assert(storage.maintain());assert.is_nil(storage.get('alice',id)) -- Stale and past retention.
    end)
    it('keeps saved domains private, deduplicated and independently editable',function()
        local first=assert(storage.save_target('alice','example.com','Production','quick'))
        local updated=assert(storage.save_target('alice','example.com',"Label'; DROP TABLE scans;--",'deep'))
        assert.equal(first.id,updated.id);assert.equal('deep',updated.profile)
        assert.equal(1,#storage.targets('alice'));assert.equal(0,#storage.targets('bob'))
        assert.equal(0,storage.delete_target('bob',first.id));assert.equal(1,#storage.targets('alice'))
        assert(storage.save_target('bob','example.com','Other workspace','quick'))
        assert.equal(1,storage.delete_target('alice',first.id));assert.equal(1,#storage.targets('bob'))
    end)
    it('caps saved domains without preventing edits at capacity',function()
        for i=1,50 do assert(storage.save_target('alice','host'..i..'.example.com','','quick')) end
        local row,err=storage.save_target('alice','overflow.example.com','','quick')
        assert.is_nil(row);assert.matches('50',err)
        assert(storage.save_target('alice','host1.example.com','Edited at capacity','deep'))
        assert.equal(50,#storage.targets('alice'))
    end)
    it('links only the owning workspace latest scan and filters the full history',function()
        assert(storage.save_target('alice','example.com','','quick'))
        local alice=assert(storage.create('alice','example.com','quick'))
        assert(storage.create('alice','another.example.com','quick'))
        assert(storage.create('bob','example.com','quick'))
        local target=storage.targets('alice')[1]
        assert.equal(alice,target.last_scan_id)
        assert.equal(1,storage.count('alice','example.com'))
        assert.equal(alice,storage.history('alice',1,'example.com')[1].id)
        assert.equal(0,#storage.history('alice',1,'missing.example.com'))
    end)
    it('expires saved domains without removing their recent reports',function()
        assert(storage.save_target('alice','example.com','','quick'))
        local id=assert(storage.create('alice','example.com','quick'))
        local db=sqlite.open(prefix..'/data/recon.db');db:exec('UPDATE saved_targets SET updated_epoch=1');db:close()
        assert(storage.maintain());assert.equal(0,#storage.targets('alice'));assert.is_not_nil(storage.get('alice',id))
    end)
    it('finds earlier domain reports even when other domains fill the current history page',function()
        local earlier=assert(storage.create('alice','example.com','quick'))
        for i=1,50 do assert(storage.create('alice','other'..i..'.example.com','quick')) end
        local latest=assert(storage.create('alice','example.com','quick'))
        assert.equal(50,#storage.history('alice',1))
        local matching=storage.history('alice',1,'example.com')
        assert.equal(2,#matching);assert.equal(latest,matching[1].id);assert.equal(earlier,matching[2].id)
    end)
    it('returns bounded domain history with ownership and exclusive cursors',function()
        local ids={}
        for i=1,52 do ids[i]=assert(storage.create('alice','example.com','quick')) end
        assert(storage.create('bob','example.com','quick'))
        assert(storage.create('alice','other.example.com','quick'))
        local recent,err,more=storage.domain_history('alice','example.com')
        assert.is_nil(err);assert.is_true(more);assert.equal(50,#recent)
        assert.equal(ids[52],recent[1].id);assert.equal(ids[3],recent[50].id)
        local earlier,_,has_more=storage.domain_history('alice','example.com',recent[50].id)
        assert.equal(2,#earlier);assert.is_false(has_more);assert.equal(ids[2],earlier[1].id)
        assert.equal(1,#storage.domain_history('bob','example.com'))
        assert.equal(0,#storage.domain_history('nobody','example.com'))
        assert.is_nil(recent[1].report);assert.is_nil(recent[1].owner)
    end)
    it('keeps unknown summary fields nullable and writes certificate metadata from the report',function()
        local old=assert(storage.create('alice','example.com','quick'))
        assert(storage.finish(old,{error='Interrupted'},'failed',10))
        local entry=storage.domain_history('alice','example.com')[1]
        assert.is_nil(entry.score);assert.is_nil(entry.dns_count);assert.is_nil(entry.tls_verified);assert.is_nil(entry.certificate_not_after)
        local id=assert(storage.create('alice','example.com','quick'))
        local sha=string.rep('a',64)
        assert(storage.finish(id,{score=0,dns={records={}},http={status=200,tls={verified=true,certificate={not_after=1800600000,fingerprint_sha256=sha}}}},'completed',15))
        local row=storage.domain_history('alice','example.com')[1]
        assert.equal(0,row.score);assert.equal(0,row.dns_count);assert.equal(1,row.tls_verified)
        assert.equal(200,row.http_status);assert.equal(1800600000,row.certificate_not_after);assert.equal(sha,row.certificate_sha256)
        assert(storage.save_target('alice','example.com','','quick'))
        assert.equal(1800600000,storage.targets('alice')[1].last_certificate_not_after)
    end)
end)
